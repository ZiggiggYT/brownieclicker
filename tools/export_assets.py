"""Copy the generated sprite sheet into the game and write js/atlas.js.

The atlas is also embedded as a script so the game works when index.html is
opened straight from disk (browsers block fetch() of JSON on file:// URLs).
Run after tools/sprites.py:  python tools/export_assets.py
"""
import json, os, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'tools', 'brownie-baker-art')
ASSETS = os.path.join(ROOT, 'assets')

os.makedirs(ASSETS, exist_ok=True)
for f in ('spritesheet.png', 'spritesheet.json'):
    shutil.copy(os.path.join(ART, f), os.path.join(ASSETS, f))
with open(os.path.join(ART, 'spritesheet.json')) as f:
    atlas = json.load(f)
with open(os.path.join(ROOT, 'js', 'atlas.js'), 'w') as f:
    f.write('// Generated by tools/export_assets.py from assets/spritesheet.json. Do not edit.\n')
    f.write('window.BB = window.BB || {};\nBB.ATLAS = ' + json.dumps(atlas, separators=(',', ':')) + ';\n')
print('exported', len(atlas['frames']), 'frames')
